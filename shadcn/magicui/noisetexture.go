package magicui

import (
	"github.com/ungerik/go-mx"
	"github.com/ungerik/go-mx/svg"
)

// NoiseTextureOptions configures a [NoiseTexture]. The zero value is
// upstream's default.
type NoiseTextureOptions struct {
	// ID is the id of the SVG <filter>, which the noise rect references as
	// url(#ID). Empty means a process-unique id from [mx.UniqueID]; pass a
	// fixed one where the markup has to be deterministic. It may only contain
	// letters, digits, '_' and '-'.
	ID string
	// Frequency is the baseFrequency of the feTurbulence; higher values give
	// finer-grained noise. 0 means 0.4.
	Frequency float64
	// Octaves is the numOctaves of the feTurbulence; more octaves add detail
	// at smaller scales. 0 means 6.
	Octaves int
	// Slope is the linear slope applied to each color channel after
	// desaturation, the contrast of the noise; 0 means 0.15.
	Slope float64
	// NoiseOpacity is the opacity of the noise layer; 0 means 0.6.
	NoiseOpacity float64
}

// NoiseTexture overlays a grainy, desaturated fractal noise, generated by an
// SVG feTurbulence filter, as an absolutely positioned layer that fills its
// positioned parent; give the content in front of it a z-index, as in
// html.Class("relative z-10"). Children are appended inside the <svg>, after
// the noise. The SVG is aria-hidden, which upstream's is not.
func NoiseTexture(opts NoiseTextureOptions, attribsChildren ...any) *mx.Element {
	id, err := svgRefID(opts.ID)
	if err != nil {
		return mx.NewErrElement(err)
	}
	slope := or(opts.Slope, 0.15)
	parts := []mx.Component{
		svg.Filter(
			svg.ID(id),
			svg.FeTurbulence(
				svg.Type("fractalNoise"),
				svg.BaseFrequency(or(opts.Frequency, 0.4)),
				svg.NumOctaves(or(opts.Octaves, 6)),
				svg.StitchTilesStitch,
			),
			svg.FeColorMatrix(svg.Type("saturate"), svg.Values("0")),
			svg.FeComponentTransfer(
				svg.FeFuncR(svg.Type("linear"), svg.Slope(slope)),
				svg.FeFuncG(svg.Type("linear"), svg.Slope(slope)),
				svg.FeFuncB(svg.Type("linear"), svg.Slope(slope)),
			),
		),
		svg.Rect(
			svg.Width("100%"),
			svg.Height("100%"),
			svg.FilterAttr("url(#"+id+")"),
			svg.Opacity(or(opts.NoiseOpacity, 0.6)),
		),
	}
	return patternSVG("noise-texture",
		"pointer-events-none absolute inset-0 z-0 size-full opacity-50 select-none dark:opacity-[0.75]",
		parts, attribsChildren)
}
