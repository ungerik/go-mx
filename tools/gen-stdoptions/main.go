// Command gen-stdoptions generates the option lists of the go-mx stdoptions
// package from Unicode CLDR data: ISO 4217 currencies, ISO 639-1 languages
// and ISO 3166-1 alpha-2 countries, each with English and German names
// sorted by the CLDR collation of their language.
//
// The data is read from the cldr-json repository at the release tag pinned
// in [cldrRelease]; bump that constant and re-run go generate in stdoptions
// to update the lists:
//
//	//go:generate go -C ../tools run ./gen-stdoptions -out ../stdoptions/cldrdata.go
//
// It lives in the tools module, not the root module, because it collates
// with golang.org/x/text, which the shipped go-mx module does not depend on.
// The generated file is plain data: sorting happens here, not at run time.
package main

import (
	"bytes"
	"context"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"io"
	"maps"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"

	"golang.org/x/text/collate"
	"golang.org/x/text/language"
)

// cldrRelease is the cldr-json release tag the lists are generated from,
// the one place the CLDR version is pinned.
const cldrRelease = "49.0.0"

const baseURL = "https://raw.githubusercontent.com/unicode-org/cldr-json/" + cldrRelease + "/cldr-json/"

// locales are the languages the names are generated in. The first one is
// the fallback of the stdoptions package.
var locales = []string{"en", "de"}

var (
	twoLower   = regexp.MustCompile(`^[a-z]{2}$`)
	twoUpper   = regexp.MustCompile(`^[A-Z]{2}$`)
	threeUpper = regexp.MustCompile(`^[A-Z]{3}$`)
)

type option struct {
	Code string
	Name string
}

func main() {
	out := flag.String("out", "cldrdata.go", "path of the generated Go file")
	flag.Parse()

	if err := run(context.Background(), *out); err != nil {
		fmt.Fprintln(os.Stderr, "gen-stdoptions:", err)
		os.Exit(1)
	}
}

func run(ctx context.Context, out string) error {
	currencyCodes, err := currentCurrencies(ctx)
	if err != nil {
		return err
	}
	aliases, err := fetchAliases(ctx)
	if err != nil {
		return err
	}
	languageCodes := iso639_1Languages(aliases)
	countryCodes, err := iso3166_1Countries(ctx, aliases)
	if err != nil {
		return err
	}

	lists := []struct {
		varName string
		codes   []string
		names   func(ctx context.Context, locale string) (map[string]string, error)
	}{
		{"currencies", currencyCodes, currencyNames},
		{"languages", languageCodes, languageNames},
		{"countries", countryCodes, countryNames},
	}

	var src bytes.Buffer
	fmt.Fprintf(&src, "// Code generated by tools/gen-stdoptions from CLDR %s; DO NOT EDIT.\n\n", cldrRelease)
	fmt.Fprintf(&src, "package stdoptions\n\nimport \"github.com/ungerik/go-mx\"\n\n")
	fmt.Fprintf(&src, "// CLDRRelease is the cldr-json release tag the option lists were generated from.\n")
	fmt.Fprintf(&src, "const CLDRRelease = %q\n\n", cldrRelease)
	fmt.Fprintf(&src, "// fallbackLanguage is the language of the names used for a context\n// that carries no supported language.\n")
	fmt.Fprintf(&src, "const fallbackLanguage = %q\n", locales[0])

	for _, list := range lists {
		fmt.Fprintf(&src, "\nvar %s = map[string][]mx.NamedOption{\n", list.varName)
		for _, locale := range locales {
			names, err := list.names(ctx, locale)
			if err != nil {
				return err
			}
			opts, err := localizedOptions(locale, list.codes, names)
			if err != nil {
				return fmt.Errorf("%s in %s: %w", list.varName, locale, err)
			}
			fmt.Fprintf(&src, "\t%q: {\n", locale)
			for _, o := range opts {
				fmt.Fprintf(&src, "\t\t{Name: %q, Value: %q},\n", o.Name, o.Code)
			}
			fmt.Fprintf(&src, "\t},\n")
		}
		fmt.Fprintf(&src, "}\n")
	}

	formatted, err := format.Source(src.Bytes())
	if err != nil {
		return fmt.Errorf("formatting generated source: %w", err)
	}
	return os.WriteFile(out, formatted, 0o644)
}

// localizedOptions pairs every code with its name in locale and sorts the
// result by the CLDR collation of locale, so "Österreich" sorts with the O
// in German and "Åland Islands" with the A in English. A code without a
// name, or two codes sharing one name, fail the generation: both would
// make a confusing option list.
func localizedOptions(locale string, codes []string, names map[string]string) ([]option, error) {
	opts := make([]option, 0, len(codes))
	seen := make(map[string]string, len(codes))
	for _, code := range codes {
		name := names[code]
		if name == "" {
			return nil, fmt.Errorf("no name for %s", code)
		}
		if other, ok := seen[name]; ok {
			return nil, fmt.Errorf("%s and %s are both named %q", other, code, name)
		}
		seen[name] = code
		opts = append(opts, option{Code: code, Name: name})
	}
	collator := collate.New(language.MustParse(locale))
	slices.SortFunc(opts, func(a, b option) int {
		if c := collator.CompareString(a.Name, b.Name); c != 0 {
			return c
		}
		return strings.Compare(a.Code, b.Code)
	})
	return opts, nil
}

// currentCurrencies returns the ISO 4217 codes that are legal tender in at
// least one region today: an entry of supplemental currencyData without a
// _to date (CLDR sets it when a currency is withdrawn, such as DEM or BGN)
// and without _tender="false" (funds codes and units of account like BOV,
// CHE, XDR, XAU or XXX).
func currentCurrencies(ctx context.Context) ([]string, error) {
	var data struct {
		Supplemental struct {
			Version      cldrVersion `json:"version"`
			CurrencyData struct {
				Region map[string][]map[string]struct {
					From   string `json:"_from"`
					To     string `json:"_to"`
					Tender string `json:"_tender"`
				} `json:"region"`
			} `json:"currencyData"`
		} `json:"supplemental"`
	}
	if err := fetchJSON(ctx, "cldr-core/supplemental/currencyData.json", &data); err != nil {
		return nil, err
	}
	if err := data.Supplemental.Version.check(); err != nil {
		return nil, err
	}
	codes := make(map[string]bool)
	for _, entries := range data.Supplemental.CurrencyData.Region {
		for _, entry := range entries {
			for code, info := range entry {
				if info.To == "" && info.Tender != "false" && threeUpper.MatchString(code) {
					codes[code] = true
				}
			}
		}
	}
	return sortedKeys(codes), nil
}

// iso639_1Languages returns the two-letter ISO 639-1 codes CLDR treats as
// canonical: the two-letter replacements of its "overlong" language aliases
// (deu → de, ger → de), which map every ISO 639-2/3 code that has an ISO
// 639-1 form to that form. Codes CLDR aliases away themselves are left out:
// the withdrawn in, iw, ji, jw and mo, the legacy sh and tl, and tw, which
// CLDR folds into the macrolanguage ak.
func iso639_1Languages(aliases *aliasData) []string {
	codes := make(map[string]bool)
	for _, alias := range aliases.Supplemental.Metadata.Alias.LanguageAlias {
		if alias.Reason == "overlong" && twoLower.MatchString(alias.Replacement) {
			codes[alias.Replacement] = true
		}
	}
	for code := range aliases.Supplemental.Metadata.Alias.LanguageAlias {
		delete(codes, code)
	}
	return sortedKeys(codes)
}

// iso3166_1Countries returns the officially assigned ISO 3166-1 alpha-2
// codes: the two-letter regions of supplemental codeMappings that carry an
// ISO 3166-1 numeric code below 900. That leaves out the exceptionally
// reserved codes without a numeric code (AC, CP, CQ, DG, EA, EZ, IC, TA,
// UN), the user-assigned ones CLDR gives a numeric code of 900–999 (AA,
// EU, QO, XA, XB, XK, ZZ), and the deprecated regions of territoryAlias
// (AN, CS, SU, YU, …).
func iso3166_1Countries(ctx context.Context, aliases *aliasData) ([]string, error) {
	var data struct {
		Supplemental struct {
			Version      cldrVersion `json:"version"`
			CodeMappings map[string]struct {
				Numeric string `json:"_numeric"`
			} `json:"codeMappings"`
		} `json:"supplemental"`
	}
	if err := fetchJSON(ctx, "cldr-core/supplemental/codeMappings.json", &data); err != nil {
		return nil, err
	}
	if err := data.Supplemental.Version.check(); err != nil {
		return nil, err
	}
	codes := make(map[string]bool)
	for code, mapping := range data.Supplemental.CodeMappings {
		if !twoUpper.MatchString(code) || mapping.Numeric == "" {
			continue
		}
		numeric, err := strconv.Atoi(mapping.Numeric)
		if err != nil {
			return nil, fmt.Errorf("numeric code %q of region %s: %w", mapping.Numeric, code, err)
		}
		if numeric < 900 {
			codes[code] = true
		}
	}
	for code := range aliases.Supplemental.Metadata.Alias.TerritoryAlias {
		delete(codes, code)
	}
	return sortedKeys(codes), nil
}

func currencyNames(ctx context.Context, locale string) (map[string]string, error) {
	var data struct {
		Main map[string]struct {
			Numbers struct {
				Currencies map[string]struct {
					DisplayName string `json:"displayName"`
				} `json:"currencies"`
			} `json:"numbers"`
		} `json:"main"`
	}
	if err := fetchJSON(ctx, "cldr-numbers-full/main/"+locale+"/currencies.json", &data); err != nil {
		return nil, err
	}
	names := make(map[string]string)
	for code, c := range data.Main[locale].Numbers.Currencies {
		names[code] = c.DisplayName
	}
	return names, nil
}

func languageNames(ctx context.Context, locale string) (map[string]string, error) {
	var data struct {
		Main map[string]struct {
			LocaleDisplayNames struct {
				Languages map[string]string `json:"languages"`
			} `json:"localeDisplayNames"`
		} `json:"main"`
	}
	if err := fetchJSON(ctx, "cldr-localenames-full/main/"+locale+"/languages.json", &data); err != nil {
		return nil, err
	}
	return data.Main[locale].LocaleDisplayNames.Languages, nil
}

// countryNames returns the standard names, not the -alt-short variants,
// which would turn the United Kingdom into "UK".
func countryNames(ctx context.Context, locale string) (map[string]string, error) {
	var data struct {
		Main map[string]struct {
			LocaleDisplayNames struct {
				Territories map[string]string `json:"territories"`
			} `json:"localeDisplayNames"`
		} `json:"main"`
	}
	if err := fetchJSON(ctx, "cldr-localenames-full/main/"+locale+"/territories.json", &data); err != nil {
		return nil, err
	}
	return data.Main[locale].LocaleDisplayNames.Territories, nil
}

type aliasData struct {
	Supplemental struct {
		Version  cldrVersion `json:"version"`
		Metadata struct {
			Alias struct {
				LanguageAlias  map[string]alias `json:"languageAlias"`
				TerritoryAlias map[string]alias `json:"territoryAlias"`
			} `json:"alias"`
		} `json:"metadata"`
	} `json:"supplemental"`
}

type alias struct {
	Replacement string `json:"_replacement"`
	Reason      string `json:"_reason"`
}

func fetchAliases(ctx context.Context) (*aliasData, error) {
	var data aliasData
	if err := fetchJSON(ctx, "cldr-core/supplemental/aliases.json", &data); err != nil {
		return nil, err
	}
	if err := data.Supplemental.Version.check(); err != nil {
		return nil, err
	}
	return &data, nil
}

// cldrVersion is the version stamp of a supplemental file, checked against
// [cldrRelease] so a moved tag cannot silently mix releases.
type cldrVersion struct {
	CLDRVersion string `json:"_cldrVersion"`
}

func (v cldrVersion) check() error {
	major, _, _ := strings.Cut(cldrRelease, ".")
	if v.CLDRVersion != major {
		return fmt.Errorf("supplemental data is CLDR %q, want %q", v.CLDRVersion, major)
	}
	return nil
}

func fetchJSON(ctx context.Context, path string, v any) error {
	ctx, cancel := context.WithTimeout(ctx, time.Minute)
	defer cancel()
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, baseURL+path, nil)
	if err != nil {
		return err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return fmt.Errorf("GET %s: %s", req.URL, resp.Status)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, 16<<20))
	if err != nil {
		return fmt.Errorf("GET %s: %w", req.URL, err)
	}
	if err := json.Unmarshal(body, v); err != nil {
		return fmt.Errorf("parsing %s: %w", path, err)
	}
	return nil
}

func sortedKeys(set map[string]bool) []string {
	return slices.Sorted(maps.Keys(set))
}
